/**
 * Object storage behind an adapter (SPEC §4). The interface mirrors S3
 * semantics (flat keys, put/get/delete) so an S3-compatible adapter can
 * replace the development disk adapter without changing callers.
 */
export interface StorageAdapter {
  readonly name: string;
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<{ body: Buffer; contentType: string } | null>;
  delete(key: string): Promise<void>;
  /** Public URL for an object (CDN / API media route). */
  publicUrl(key: string): string;
}

export const STORAGE = Symbol('STORAGE');

export const MEDIA_TYPES: Record<string, string> = {
  webp: 'image/webp',
  jpg: 'image/jpeg',
  png: 'image/png',
  avif: 'image/avif',
};

/**
 * Keys are generated by the server (random ids), never taken from users:
 * lowercase segments, no "..", a known image extension.
 */
const KEY = /^[a-z0-9]+(?:[/_-][a-z0-9]+)*\.(webp|jpg|png|avif)$/;

export function isValidStorageKey(key: string): boolean {
  return key.length <= 200 && KEY.test(key);
}

export function contentTypeForKey(key: string): string | null {
  const ext = key.split('.').pop() ?? '';
  return MEDIA_TYPES[ext] ?? null;
}
